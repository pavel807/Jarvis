/**
 * Таймлайн заставки реактора — единственный источник правды для сцены и
 * интерфейса.
 *
 * Модуль намеренно без Three.js: ради одной длительности тянуть 800 КБ чанк
 * сценой в App.svelte или подписи загрузки нельзя.
 *
 * Сюжет в два «хопа»: сборка проявляется там же, где стоит, и остаётся на
 * своих местах — детали только расслаиваются вдоль собственной высоты
 * реактора (нормаль к треугольной грани, все в одну сторону — как страницы,
 * снятые с корешка лежащей на столе книги), затем так же целиком захлопываются
 * обратно и сборка одним рывком доворачивается к рабочему виду → розжиг и
 * раскрытие интерфейса. Никакой сборки из разлетевшихся кусков: узел не меняет
 * ни X, ни Y, только Z.
 */

/** Проявление сборки из темноты: лёгкий зум с перелётом. */
const APPEAR = { at: 0.0, dur: 0.35 };
/** Первое «хоп»: слои выходят из грани вдоль собственной высоты, от ядра к корпусу. */
const SPREAD = { at: 0.35, dur: 0.4, stagger: 0.42 };
/** Второе «хоп»: слои захлопываются, порядок обратный (корпус последний). */
const GATHER = { at: 1.25, dur: 0.35, stagger: 0.32 };
/** Щелчок узлов на место: лёгкий присед, а не прилёт издалека. */
const DOCK = { at: 1.42, stagger: 0.08, dur: 0.26 };
/** Доворот во фронт с перелётом, возврат камеры и розжиг. */
const TURN = { at: 1.8, dur: 0.5 };

export const INTRO = { APPEAR, SPREAD, GATHER, DOCK, TURN };

/** Полная длительность заставки, секунды. */
export const INTRO_DURATION = TURN.at + TURN.dur;

export const clamp01 = (v: number) => Math.max(0, Math.min(1, v));

/** Прогресс фазы 0..1 в абсолютном времени анимации. */
export function phase(t: number, at: number, dur: number): number {
  return clamp01((t - at) / dur);
}

/** Вход с перелётом: деталь «прищёлкивается» в посадочное место. */
export function easeOutBack(p: number): number {
  if (p <= 0) return 0;
  if (p >= 1) return 1;
  const c1 = 0.9;
  const x = p - 1;
  return 1 + (c1 + 1) * x * x * x + c1 * x * x;
}

/** Резкий выброс с короткой стабилизацией: деталь выстреливает на позицию. */
export function easeOutSnap(p: number): number {
  if (p <= 0) return 0;
  if (p >= 1) return 1;
  return 1 - Math.pow(1 - p, 3.2);
}

/** Плавный разворот всей сборки к рабочему виду. */
export function easeInOutCubic(p: number): number {
  return p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2;
}
