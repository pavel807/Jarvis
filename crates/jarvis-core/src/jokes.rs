/// Похоже ли сказанное на просьбу рассказать шутку.
pub fn is_joke_request(text: &str) -> bool {
    let t = normalize(text);
    if t.is_empty() {
        return false;
    }
    // «Не рассказывай шутку» — не просьба. Проверка простая и намеренно
    // осторожная: лучше пропустить фразу в LLM, чем пошутить против воли.
    if t.contains("не рассказыв")
        || t.contains("не надо шут")
        || t.contains("без шут")
        || t.contains("не шути")
    {
        return false;
    }
    const TRIGGERS: &[&str] = &[
        "расскажи шутку",
        "расскажи мне шутку",
        "расскажи анекдот",
        "расскажи мне анекдот",
        "пошути",
        "пошутить",
        "еще шутку",
        "еще анекдот",
        "хочу шутку",
        "хочу анекдот",
        "знаешь шутку",
        "знаешь анекдот",
        "рассмеши",
        "развесели",
        "развлеки",
    ];
    if TRIGGERS.iter().any(|trigger| t.contains(trigger)) {
        return true;
    }
    // Одно слово-просьба: «шутку», «анекдот». Вопросы о шутках («почему
    // шутка смешная») сюда не попадают — там больше слов и есть «почему».
    matches!(
        t.as_str(),
        "шутка" | "шутку" | "анекдот" | "анекдот пожалуйста" | "шутку пожалуйста"
    )
}

/// Рассказать следующую шутку. `Err` — честная причина, а не выдуманный
/// текст: если база недоступна, пользователь должен это услышать.
pub fn tell() -> Result<String, String> {
    crate::db::next_joke()
}

/// Нормализация для распознавания: нижний регистр, ё → е, схлопнутые
/// пробелы. Пунктуация по краям слов не мешает.
fn normalize(text: &str) -> String {
    let lower = text.to_lowercase().replace('ё', "е");
    lower
        .split(|c: char| !c.is_alphanumeric() && c != ' ')
        .collect::<Vec<_>>()
        .join(" ")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recognizes_joke_requests() {
        for phrase in [
            "Джарвис, расскажи шутку",
            "расскажи анекдот пожалуйста",
            "пошути",
            "ещё шутку",
            "хочу анекдот",
            "рассмеши меня",
        ] {
            assert!(is_joke_request(phrase), "должно распознаться: {phrase}");
        }
    }

    #[test]
    fn does_not_hijack_other_questions() {
        for phrase in [
            "почему шутка смешная",
            "расскажи, как работает шутка",
            "не рассказывай шутку",
            "открой ютуб",
        ] {
            assert!(!is_joke_request(phrase), "не должно распознаться: {phrase}");
        }
    }

    #[test]
    fn seed_is_not_empty_and_short_enough_for_tts() {
        assert!(SEED.len() >= 20);
        for joke in SEED {
            assert!(!joke.trim().is_empty());
            // Слишком длинную шутку TTS превращает в монолог.
            assert!(joke.chars().count() <= 220, "слишком длинная: {joke}");
        }
    }
}
