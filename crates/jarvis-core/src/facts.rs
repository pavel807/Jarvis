/// Похоже ли сказанное на просьбу рассказать факт.
pub fn is_fact_request(text: &str) -> bool {
    let t = normalize(text);
    if t.is_empty() {
        return false;
    }
    // «Не рассказывай факты» — не просьба: осторожная проверка, лучше
    // пропустить фразу в LLM, чем лезть с фактом против воли.
    if t.contains("не рассказыв") || t.contains("не надо факт") || t.contains("без факт") {
        return false;
    }
    const TRIGGERS: &[&str] = &[
        "расскажи факт",
        "расскажи мне факт",
        "расскажи интересный факт",
        "расскажи полезный факт",
        "расскажи любой факт",
        "расскажи факты",
        "дай факт",
        "давай факт",
        "хочу факт",
        "хочу интересный факт",
        "знаешь факт",
        "какой нибудь факт",
        "какой-нибудь факт",
        "интересный факт",
        "полезный факт",
        "еще факт",
        "еще один факт",
        "еще интересный факт",
        "факт про что нибудь",
    ];
    if TRIGGERS.iter().any(|trigger| t.contains(trigger)) {
        return true;
    }
    // Однословные просьбы: «факт», «факты», «факт пожалуйста».
    matches!(
        t.as_str(),
        "факт" | "факты" | "факт пожалуйста" | "факты пожалуйста" | "фактик"
    )
}

/// Рассказать следующий факт. `Err` — честная причина, а не выдумка.
pub fn tell() -> Result<String, String> {
    crate::db::next_fact()
}

/// Нормализация для распознавания: нижний регистр, ё → е, схлопнутые
/// пробелы. Согласована с проверкой шуток — дефис не мешает.
fn normalize(text: &str) -> String {
    let lower = text.to_lowercase().replace('ё', "е").replace('-', " ");
    lower
        .split(|c: char| !c.is_alphanumeric() && c != ' ')
        .collect::<Vec<_>>()
        .join(" ")
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn recognizes_fact_requests() {
        for phrase in [
            "Джарвис, расскажи интересный факт",
            "расскажи факт",
            "какой-нибудь полезный факт",
            "хочу факт",
            "ещё один факт",
            "факт пожалуйста",
        ] {
            assert!(is_fact_request(phrase), "должно распознаться: {phrase}");
        }
    }

    #[test]
    fn does_not_hijack_other_questions() {
        for phrase in [
            "расскажи про факты истории",
            "что такое факт",
            "не рассказывай факты",
            "открой ютуб",
            "почему факт такой",
        ] {
            assert!(!is_fact_request(phrase), "не должно распознаться: {phrase}");
        }
    }
}
