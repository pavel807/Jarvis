//! autocore — ядро, управляющее настольными приложениями как человек:
//! смотрит на интерфейс через accessibility-API, находит элемент, действует,
//! проверяет результат, учится на ошибках.
//!
//! Жёсткие правила (см. спецификацию §13):
//! - ни одного вызова LLM и ни одного скриншота в основном цикле;
//! - успех действия = наблюдаемое следствие, а не `Ok(())`;
//! - повтор только при `Delivery::NotDelivered`; при `Unknown` — сначала
//!   наблюдение;
//! - каждое «не умею» названо с платформой, причиной и следующим шагом.
//!
//! Слои (этапы спецификации):
//! - [`smi`] — A1, устойчивый идентификатор элемента;
//! - [`est`] — A2, теневое дерево на событиях, без повторных обходов;
//! - [`simhash`] — A3, «экран изменился?» за O(1);
//! - [`doctor`] — отчёт о возможностях платформы и правах;
//! - [`fake`] — синтетический десктоп: все алгоритмы тестируются без ОС.
//!
//! Понимание команд (A4), поиск цели (A5), выученные планы (A6), выбор
//! способа доставки (A7) и отслеживание деградации (A8) — следующие этапы.

pub mod capture;
pub mod doctor;
pub mod est;
pub mod fake;
pub mod simhash;
pub mod smi;

/// Порог SimHash по умолчанию: расстояние Хэмминга, ниже которого экран
/// считаем «тем же». Калибровка на приёмочном дереве (§3): скролл даёт
/// ровно 0, смена метки — 5, диалог — 6; порог 4 отделяет реальные
/// изменения от перерисовки. Настраивается: приложение с постоянно
/// меняющимися метками поднимает его. Гейт применяется к поддереву
/// окна/приложения, а не ко всему десктопу: на тысяче узлов знак-голос
/// глохнет (счётчики толстые), на масштабе окна чувствительность верна.
pub const SIMHASH_DEFAULT_THRESHOLD: u32 = 4;

/// Версия формата персистентного состояния (§8): при несовпадении —
/// отбросить и начать заново, не падать.
pub const STATE_FORMAT_VERSION: u32 = 1;
